#!/usr/bin/env python3
"""Reads Meshy animation GLBs (<char>_<clip>.glb) and writes anims.js: per character, per clip, bone rotations
sampled at 30 fps (int16 quaternions) plus the hips height offset. Only the motion is kept, not the mesh."""
import sys, os, json, struct, glob, base64
import numpy as np
src, out = sys.argv[1], sys.argv[2]
FPS = 30
CT = {5126: ('f4', 4), 5123: ('u2', 2), 5121: ('u1', 1), 5122: ('i2', 2), 5120: ('i1', 1), 5125: ('u4', 4)}
NC = {'SCALAR': 1, 'VEC3': 3, 'VEC4': 4}
def load(path):
    b = open(path, 'rb').read()
    jl = struct.unpack_from('<I', b, 12)[0]; js = json.loads(b[20:20 + jl]); binoff = 20 + jl + 8
    def acc(i):
        a = js['accessors'][i]; bv = js['bufferViews'][a['bufferView']]; dt, sz = CT[a['componentType']]; n = NC[a['type']]
        off = binoff + bv.get('byteOffset', 0) + a.get('byteOffset', 0); stride = bv.get('byteStride', sz * n)
        raw = np.frombuffer(b, dtype=np.uint8, count=(a['count'] - 1) * stride + sz * n, offset=off)
        if stride == sz * n: arr = raw.view('<' + dt).reshape(a['count'], n)
        else: arr = np.stack([raw[i * stride:i * stride + sz * n].view('<' + dt) for i in range(a['count'])])
        arr = arr.astype(np.float32)
        if a.get('normalized'): arr = arr / {'i2': 32767.0, 'u2': 65535.0, 'i1': 127.0, 'u1': 255.0}[dt]
        return arr
    return js, acc
def sample(times, vals, t, quat):
    times = times[:, 0]; i = np.clip(np.searchsorted(times, t, side='right') - 1, 0, len(times) - 1); j = np.minimum(i + 1, len(times) - 1)
    span = np.maximum(times[j] - times[i], 1e-6); w = np.clip((t - times[i]) / span, 0, 1)[:, None]
    a, c = vals[i], vals[j].copy()
    if quat:
        flip = (a * c).sum(1) < 0; c[flip] *= -1
    r = a * (1 - w) + c * w
    if quat: r /= np.linalg.norm(r, axis=1, keepdims=True)
    return r
res = {}
for path in sorted(glob.glob(os.path.join(src, '*.glb'))):
    char, clip = os.path.basename(path)[:-4].split('_', 1)
    js, acc = load(path)
    if not js.get('animations'): print('no animation in', path); continue
    an = max(js['animations'], key=lambda a: len(a['channels']))
    dur = 0; rot = {}; hips = None
    for ch in an['channels']:
        s = an['samplers'][ch['sampler']]; node = js['nodes'][ch['target']['node']]; name = node.get('name', ''); p = ch['target']['path']
        tm = acc(s['input']); v = acc(s['output'])
        if s.get('interpolation') == 'CUBICSPLINE': v = v[1::3]
        dur = max(dur, float(tm[-1, 0]))
        if p == 'rotation': rot[name] = (tm, v)
        elif p == 'translation' and name == 'Hips': hips = (tm, v, node.get('translation', [0, 0, 0]))
    n = max(2, int(round(dur * FPS)) + 1); t = np.linspace(0, dur, n).astype(np.float32)
    names = sorted(rot)
    q = np.stack([sample(rot[b][0], rot[b][1], t, True) for b in names], axis=1)  # frames x bones x 4
    e = {'n': n, 'dur': round(dur, 4), 'bones': names, 'rot': base64.b64encode(np.round(q * 32767).astype('<i2').tobytes()).decode()}
    if hips is not None:
        h = sample(hips[0], hips[1], t, False); e['hy'] = [round(float(x), 2) for x in (h[:, 1] - hips[2][1])]
    res.setdefault(char, {})[clip] = e
with open(out, 'w') as f:
    f.write('// generated by tools/extract_anims.py from Meshy animation files - do not edit\nwindow.CLASH_ANIMS = ' + json.dumps(res, separators=(',', ':')) + ';\n')
print({c: len(v) for c, v in res.items()}, os.path.getsize(out) // 1024, 'KB')
