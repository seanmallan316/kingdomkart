#!/usr/bin/env python3
"""Packs sfx/*.mp3 into sfx.js as base64 so the sounds load anywhere (web page, local file, Android APK)."""
import base64, glob, os
here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = ["// generated by tools/build_sfx.py from sfx/*.mp3 - do not edit", "window.CLASH_SFX = {"]
for f in sorted(glob.glob(os.path.join(here, 'sfx', '*.mp3'))):
    out.append("  %s: '%s'," % (os.path.splitext(os.path.basename(f))[0], base64.b64encode(open(f, 'rb').read()).decode()))
out.append("};")
open(os.path.join(here, 'sfx.js'), 'w').write("\n".join(out) + "\n")
