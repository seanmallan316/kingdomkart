#!/usr/bin/env python3
"""Packs fam/*.webp (the family banner, one panel per person) into famjs.js as data URIs so it works from file://."""
import base64, glob, os
here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = ["// generated by tools/build_fam.py from fam/*.webp - do not edit", "window.CLASH_FAM = {"]
for f in sorted(glob.glob(os.path.join(here, 'fam', '*.webp'))):
    out.append("  %s: 'data:image/webp;base64,%s'," % (os.path.splitext(os.path.basename(f))[0], base64.b64encode(open(f, 'rb').read()).decode()))
out.append("};")
open(os.path.join(here, 'famjs.js'), 'w').write("\n".join(out) + "\n")
