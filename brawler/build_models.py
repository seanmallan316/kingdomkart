#!/usr/bin/env python3
"""Packs models/*.glb into models.js as base64 so the game loads them anywhere (file://, web page, Android APK)."""
import base64, glob, os
here = os.path.dirname(os.path.abspath(__file__))
out = ["// generated by build_models.py from models/*.glb - do not edit", "window.CLASH_MODELS = {"]
for f in sorted(glob.glob(os.path.join(here, 'models', '*.glb'))):
    out.append("  %s: '%s'," % (os.path.splitext(os.path.basename(f))[0], base64.b64encode(open(f, 'rb').read()).decode()))
out.append("};")
open(os.path.join(here, 'models.js'), 'w').write("\n".join(out) + "\n")
