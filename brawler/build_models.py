#!/usr/bin/env python3
"""Packs each models/<id>.glb into modeljs/<id>.js as base64, so the game loads them anywhere (web page or a local
file opened on a PC). One file per fighter keeps each file small enough to host."""
import base64, glob, os
here = os.path.dirname(os.path.abspath(__file__))
os.makedirs(os.path.join(here, 'modeljs'), exist_ok=True)
for f in sorted(glob.glob(os.path.join(here, 'models', '*.glb'))):
    name = os.path.splitext(os.path.basename(f))[0]
    with open(os.path.join(here, 'modeljs', name + '.js'), 'w') as o:
        o.write("// generated by build_models.py - do not edit\n(window.CLASH_MODELS = window.CLASH_MODELS || {}).%s = '%s';\n" % (name, base64.b64encode(open(f, 'rb').read()).decode()))
