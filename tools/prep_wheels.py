#!/usr/bin/env python3
"""Cuts the wheels out of the kart pictures (positions from tools/wheels.txt) so the game can spin them.
For every picture listed it writes content/img/wheels_<picture>.png: one 128x128 cell per wheel, the wheel's ellipse
stretched into a circle of radius 0.42 (the margin stays transparent so the game can rotate the picture freely),
and src/game/wheels_gen.h with the positions. Also writes check sheets into the scratch folder given as argument."""
import os, sys
from PIL import Image, ImageDraw
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMG = os.path.join(ROOT, "content", "img")
CELL, R = 128, 0.42
rows = []
for line in open(os.path.join(ROOT, "tools", "wheels.txt")):
    line = line.split("#")[0].split()
    if len(line) < 6: continue
    name, spin = line[0], int(line[1]); nums = [float(x) for x in line[2:]]
    wheels = [tuple(nums[i:i + 4]) for i in range(0, len(nums) - 3, 4)][:3]
    src = os.path.join(IMG, name + ".png")
    if not os.path.exists(src): print(f"  {name}: picture missing, skipped"); continue
    im = Image.open(src).convert("RGBA"); W, H = im.size
    atlas = Image.new("RGBA", (CELL * len(wheels), CELL), (0, 0, 0, 0))
    for n, (cx, cy, rx, ry) in enumerate(wheels):
        # the ellipse in pixels, cut out and stretched to a circle of radius R*CELL
        x0, y0, x1, y1 = cx * W - rx * W, cy * H - ry * H, cx * W + rx * W, cy * H + ry * H
        d = int(2 * R * CELL)
        piece = im.crop((int(x0), int(y0), int(x1), int(y1))).resize((d, d), Image.LANCZOS)
        mask = Image.new("L", (d, d), 0); ImageDraw.Draw(mask).ellipse((0, 0, d - 1, d - 1), fill=255)
        a = piece.getchannel("A"); a = Image.composite(a, Image.new("L", (d, d), 0), mask); piece.putalpha(a)
        off = (CELL - d) // 2
        atlas.paste(piece, (n * CELL + off, off), piece)
    atlas.save(os.path.join(IMG, "wheels_" + name + ".png"), optimize=True)
    rows.append((name, spin, wheels))
    print(f"  {name}: {len(wheels)} wheels")
with open(os.path.join(ROOT, "src", "game", "wheels_gen.h"), "w") as f:
    f.write("// wheels_gen.h - generated by tools/prep_wheels.py from tools/wheels.txt: where the wheels are in each kart picture\n")
    f.write("typedef struct { const char *picture; int n, spin; float cx[3], cy[3], rx[3], ry[3]; } WheelDef;\n")
    f.write("static const WheelDef WHEEL_DEFS[] = {\n")
    for name, spin, wheels in rows:
        cx = ", ".join(f"{w[0]:.3f}f" for w in wheels); cy = ", ".join(f"{w[1]:.3f}f" for w in wheels); rx = ", ".join(f"{w[2]:.3f}f" for w in wheels); ry = ", ".join(f"{w[3]:.3f}f" for w in wheels)
        f.write(f'    {{"{name}", {len(wheels)}, {spin}, {{{cx}}}, {{{cy}}}, {{{rx}}}, {{{ry}}}}},\n')
    f.write("};\n#define NUM_WHEEL_DEFS (int)(sizeof WHEEL_DEFS / sizeof WHEEL_DEFS[0])\n")
# check sheets: the ellipses drawn over the pictures
if len(sys.argv) > 1:
    out = sys.argv[1]; os.makedirs(out, exist_ok=True)
    for chunk in range(0, len(rows), 6):
        part = rows[chunk:chunk + 6]; sh = Image.new("RGB", (400 * 3, 300 * ((len(part) + 2) // 3)), (40, 40, 40))
        for i, (name, spin, wheels) in enumerate(part):
            im = Image.open(os.path.join(IMG, name + ".png")).convert("RGBA").resize((400, 300)); bg = Image.new("RGBA", im.size, (70, 70, 70, 255)); bg.alpha_composite(im)
            d = ImageDraw.Draw(bg)
            for (cx, cy, rx, ry) in wheels: d.ellipse((cx * 400 - rx * 400, cy * 300 - ry * 300, cx * 400 + rx * 400, cy * 300 + ry * 300), outline=(0, 255, 0), width=2)
            d.text((5, 5), name, fill="yellow")
            sh.paste(bg.convert("RGB"), ((i % 3) * 400, (i // 3) * 300))
        sh.save(os.path.join(out, f"wheelcheck_{chunk // 6}.png"))
