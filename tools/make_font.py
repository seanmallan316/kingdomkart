#!/usr/bin/env python3
"""Builds the game's text font: content/img/font_hd.png (a grid of glyphs, white with a dark outline, so text reads
over any background and can be tinted) and src/render/font_hd.h (how wide each glyph is). The glyph set is FONT_CHARS
from src/render/batch.h; the game falls back to its built-in pixel font when font_hd.png is missing.
Uses DejaVu Sans Bold (free license) from the system."""
import os
from PIL import Image, ImageDraw, ImageFont, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.,!?:-'/+()"
COLS, CW, CH = 16, 64, 80          # grid: 16 columns, cells 64 wide and 80 tall
FONT_PX = 62                        # cap height comes out near 52 px: a little smaller than the old blocky font, much bolder
OUTLINE = 3
font = None
for path in ["/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf"]:
    if os.path.exists(path): font = ImageFont.truetype(path, FONT_PX); break
if font is None: raise SystemExit("no bold font found")

rows = (len(CHARS) + COLS - 1) // COLS
W, H = COLS * CW, 256 if rows * CH <= 256 else 512
atlas = Image.new("RGBA", (W, H), (0, 0, 0, 0))
advances = []
asc, desc = font.getmetrics()
baseline = 60                       # cap tops land near y = 10, commas and parentheses have room below
for i, c in enumerate(CHARS):
    cx, cy = (i % COLS) * CW, (i // COLS) * CH
    l, t, r, b = font.getbbox(c)
    adv = (r - l) + 2 * OUTLINE + 6
    # draw the glyph into its own tile: dark outline first, white fill on top
    tile = Image.new("RGBA", (CW, CH), (0, 0, 0, 0))
    d = ImageDraw.Draw(tile)
    x = OUTLINE + 3 - l
    y = baseline - asc
    for dx in range(-OUTLINE, OUTLINE + 1):
        for dy in range(-OUTLINE, OUTLINE + 1):
            if dx * dx + dy * dy <= OUTLINE * OUTLINE + 1: d.text((x + dx, y + dy), c, font=font, fill=(20, 16, 30, 255))
    d.text((x, y), c, font=font, fill=(255, 255, 255, 255))
    atlas.paste(tile, (cx, cy), tile)
    advances.append(min(adv, CW))
# a solid white block in the bottom-right corner: batch_rect() draws plain rectangles from it (WHITE_U/WHITE_V in batch.h)
ImageDraw.Draw(atlas).rectangle((W - 64, H - 64, W - 1, H - 1), fill=(255, 255, 255, 255))
atlas.save(os.path.join(ROOT, "content", "img", "font_hd.png"), optimize=True)
with open(os.path.join(ROOT, "src", "render", "font_hd.h"), "w") as f:
    f.write("// font_hd.h - generated by tools/make_font.py: the glyph grid in content/img/font_hd.png\n")
    f.write(f"#define FONT_HD_COLS {COLS}\n#define FONT_HD_CW {CW}\n#define FONT_HD_CH {CH}\n#define FONT_HD_W {W}\n#define FONT_HD_H {H}\n")
    f.write("static const unsigned char FONT_HD_ADV[] = {" + ", ".join(str(a) for a in advances) + "};\n")
print(f"font_hd.png {W}x{H}, {len(CHARS)} glyphs, advances {min(advances)}..{max(advances)}")
