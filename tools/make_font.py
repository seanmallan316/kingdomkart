#!/usr/bin/env python3
"""Builds the game's text font: content/img/font_hd.png (a grid of glyphs, white with a dark outline, so text reads
over any background and can be tinted) and src/render/font_hd.h (how wide each glyph is). The glyph set is FONT_CHARS
from src/render/batch.h; the game falls back to its built-in pixel font when font_hd.png is missing.
Uses DejaVu Sans Bold (free license) from the system."""
import os
from PIL import Image, ImageDraw, ImageFont, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.,!?:-'/+()"
COLS, CW, CH = 16, 64, 80          # grid: 16 columns, cells 64 wide and 80 tall
FONT_PX = 62                        # cap height comes out near 52 px: a little smaller than the old blocky font, much bolder
OUTLINE = 3
font = None
for path in ["/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf"]:
    if os.path.exists(path): font = ImageFont.truetype(path, FONT_PX); break
if font is None: raise SystemExit("no bold font found")

rows = (len(CHARS) + COLS - 1) // COLS
W, H = COLS * CW, 512                # top half: white outlined text; bottom half (from y = 256): gold heading letters
atlas = Image.new("RGBA", (W, H), (0, 0, 0, 0))
GOLD_Y = 256
# Sean's gold style (kingdom_kart_gold_style_package): gradient fill, bronze stroke, dark extrusion, slanted heavy letters
GRAD = [(0.00, (255, 243, 164)), (0.19, (255, 225, 107)), (0.39, (255, 202, 50)), (0.57, (232, 154, 19)), (0.72, (255, 221, 85)), (1.00, (185, 104, 12))]
def grad_color(t):
    for (t0, c0), (t1, c1) in zip(GRAD, GRAD[1:]):
        if t <= t1:
            u = (t - t0) / (t1 - t0) if t1 > t0 else 0
            return tuple(int(c0[i] + (c1[i] - c0[i]) * u) for i in range(3))
    return GRAD[-1][1]
def gold_tile(c):
    """one gold letter: slanted, with a bronze stroke, a dark extrusion down-right and a soft shadow"""
    big = Image.new("L", (CW * 2, CH * 2), 0); d = ImageDraw.Draw(big)
    l, t, r, b = font.getbbox(c); x = OUTLINE + 2 - l; y = baseline - asc
    d.text((x * 2, y * 2), c, font=font2, fill=255)
    big = big.transform(big.size, Image.AFFINE, (1, -0.12, 0.12 * 2 * baseline, 0, 1, 0), resample=Image.BICUBIC)   # slant
    mask = big.resize((CW, CH), Image.LANCZOS)
    fill = Image.new("RGBA", (CW, CH), (0, 0, 0, 0)); px = fill.load(); mk = mask.load()
    top, bot = baseline - 50, baseline
    for yy in range(CH):
        col = grad_color(min(1, max(0, (yy - top) / (bot - top))))
        for xx in range(CW):
            a = mk[xx, yy]
            if a: px[xx, yy] = (col[0], col[1], col[2], a)
    tile = Image.new("RGBA", (CW, CH), (0, 0, 0, 0))
    stroke = Image.new("RGBA", (CW, CH), (0, 0, 0, 0))
    for dx in range(-OUTLINE, OUTLINE + 1):
        for dy in range(-OUTLINE, OUTLINE + 1):
            if dx * dx + dy * dy <= OUTLINE * OUTLINE + 1: stroke.paste((117, 64, 20, 255), (dx, dy), mask)
    shadow = Image.new("RGBA", (CW, CH), (0, 0, 0, 0))
    for dy in range(1, 6): shadow.paste((93, 43, 13, 255), (dy // 2, dy), mask)         # extrusion
    soft = Image.new("RGBA", (CW, CH), (0, 0, 0, 0)); soft.paste((20, 10, 0, 170), (2, 8), mask); soft = soft.filter(ImageFilter.GaussianBlur(2))
    tile.alpha_composite(soft); tile.alpha_composite(shadow); tile.alpha_composite(stroke); tile.alpha_composite(fill)
    return tile
font2 = ImageFont.truetype(font.path, FONT_PX * 2)
advances = []
asc, desc = font.getmetrics()
baseline = 60                       # cap tops land near y = 10, commas and parentheses have room below
for i, c in enumerate(CHARS):
    cx, cy = (i % COLS) * CW, (i // COLS) * CH
    l, t, r, b = font.getbbox(c)
    adv = (r - l) + 2 * OUTLINE + 6
    # draw the glyph into its own tile: dark outline first, white fill on top
    tile = Image.new("RGBA", (CW, CH), (0, 0, 0, 0))
    d = ImageDraw.Draw(tile)
    x = OUTLINE + 3 - l
    y = baseline - asc
    for dx in range(-OUTLINE, OUTLINE + 1):
        for dy in range(-OUTLINE, OUTLINE + 1):
            if dx * dx + dy * dy <= OUTLINE * OUTLINE + 1: d.text((x + dx, y + dy), c, font=font, fill=(20, 16, 30, 255))
    d.text((x, y), c, font=font, fill=(255, 255, 255, 255))
    atlas.paste(tile, (cx, cy), tile)
    g = gold_tile(c); atlas.paste(g, (cx, cy + GOLD_Y), g)
    advances.append(min(adv, CW))
# a solid white block in the bottom-right corner: batch_rect() draws plain rectangles from it (WHITE_U/WHITE_V in batch.h)
ImageDraw.Draw(atlas).rectangle((W - 64, H - 100, W - 1, H - 1), fill=(255, 255, 255, 255))
atlas.save(os.path.join(ROOT, "content", "img", "font_hd.png"), optimize=True)
with open(os.path.join(ROOT, "src", "render", "font_hd.h"), "w") as f:
    f.write("// font_hd.h - generated by tools/make_font.py: the glyph grid in content/img/font_hd.png\n")
    f.write(f"#define FONT_HD_COLS {COLS}\n#define FONT_HD_CW {CW}\n#define FONT_HD_CH {CH}\n#define FONT_HD_W {W}\n#define FONT_HD_H {H}\n#define FONT_HD_GOLD_Y {GOLD_Y}\n")
    f.write("static const unsigned char FONT_HD_ADV[] = {" + ", ".join(str(a) for a in advances) + "};\n")
print(f"font_hd.png {W}x{H}, {len(CHARS)} glyphs, advances {min(advances)}..{max(advances)}")
